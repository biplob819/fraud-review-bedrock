def self_test() -> int:
    failures = 0

    def expect(name: str, ok: bool) -> None:
        nonlocal failures
        failures += 0 if ok else 1
        print(f"  [{'ok' if ok else 'WRONG'}] {name}")

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        page = root / "p.md"
        for name, (text, should_fail) in SELF_TEST_CASES.items():
            page.write_text(text + "\n", encoding="utf-8")
            got = bool(check([page], root))
            expect(f"{'fails' if should_fail else 'passes'} on {name}", got == should_fail)
        html_page = root / "p.html"
        html_page.write_text(
            "<section><h2>A</h2><p>on simulated data</p><b>97%</b></section>\n", encoding="utf-8"
        )
        expect("an html panel with its label passes", not check([html_page], root))
        html_page.write_text("<section><h2>A</h2><b>97%</b></section>\n", encoding="utf-8")
        expect("an html panel without the label fails", bool(check([html_page], root)))
        html_page.write_text(
            "<section><b>97%</b></section><section><p>simulated</p></section>\n", encoding="utf-8"
        )
        expect("a label in another panel does not count", bool(check([html_page], root)))
        page.write_text("Intro\r\nRecall 97%.\r\n", encoding="utf-8", newline="")
        expect(
            "CRLF line numbers match the editor",
            check([page], root) == ["p.md:2: 97% has no simulated label"],
        )
        page.write_text("Intro &#10; more\nRecall 97%.\n", encoding="utf-8")
        expect(
            "an entity newline does not shift line numbers",
            check([page], root) == ["p.md:2: 97% has no simulated label"],
        )
        page.write_text("Intro\nsecond\nRecall 97%.\n", encoding="utf-8")
        expect(
            "reports the metric's own line",
            check([page], root) == ["p.md:3: 97% has no simulated label"],
        )
        expect("missing listed file fails", bool(check([root / "nope.md"], root)))
        try:
            published_files(root)
            expect("missing listing fails", False)
        except ListingError:
            expect("missing listing fails", True)
        (root / "docs").mkdir()
        (root / LIST_FILE).write_text("../outside.md\n", encoding="utf-8")
        try:
            published_files(root)
            expect("path outside the repo fails", False)
        except ListingError:
            expect("path outside the repo fails", True)
    print("self-test", "PASSED" if failures == 0 else f"FAILED ({failures})")
    return 0 if failures == 0 else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args(argv)
    if args.self_test:
        return self_test()
    try:
        files = published_files()
    except ListingError as exc:
        print(f"honesty: FAIL — {exc}")
        return 1
    problems = check(files)
    for p in problems:
        print(p)
    print(f"honesty: {len(files)} files, {len(problems)} problems")
    return 1 if problems else 0


