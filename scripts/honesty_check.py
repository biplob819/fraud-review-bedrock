#!/usr/bin/env python3
"""Honesty gate: every number in a published artifact carries the simulated-data label.

Published artifacts are listed one repo-relative path per line in docs/published.txt.
Blank lines and lines starting with `#` are ignored; ` #` starts a trailing comment.
A missing listing is a failure: from W0.1 on, the repo always publishes something.

A metric is a percentage (`12%`, `12.5 percent`, `12 pct`), a money amount (`$4`, `$.50`,
`US$4`, `USD 4`, `4 USD`, `€4`, `£4`) or a rate per thousand (`per 1,000`, `per 1k`,
`per thousand`). Each line holding a metric must itself say "simulated" (NFR5). Negated
labels ("not simulated", "non-simulated") and labels inside HTML comments do not count.

The file is parsed as CommonMark (as GitHub renders it). Metrics are looked for in everything
a reader sees: prose, tables, code and visible HTML text. The label must be visible prose on the
same source line: a text node outside code, HTML elements, autolinks, images, URLs and link or
footnote ids, and not negated (a negator earlier in the same sentence voids it).
Purpose: catch a number whose label was forgotten or lost, not a deliberately misleading
author. In a paragraph where the parser hides a line break (inside a code span, link title or
image alt), no label counts. Known limits: negation spanning source lines or worded outside the
case table; a number and its unit split across two source lines; money or rates written wholly
in words beyond the listed forms; a per-thousand rate whose number is more than one word away;
GitHub-only syntax (footnote definitions, bare-email autolinks) is read as plain CommonMark.
Tables are read from the whole document rendered to HTML (as a browser builds them) and each is
judged when it ends. A number cell is a metric when its row, its column header, the corner cell,
a title row or the caption names a unit. A header row is inside <thead>, or, before any data
row, has two or more cells whose filled cells are all <th>; once data starts, rows outside
<thead> are data; consecutive header rows merge; a one-cell row is a title or section label.
Table limits: a number cell holds only a number (optionally with `~ ≈ + -`); `colspan` and
`rowspan` are not followed; a section row's unit is not carried to later rows.
Published artifacts are generated by one formatter
(D-14), which writes the label on the same line, so these forms should not occur.

E2.3 extends this check so every metric must also match results/<run_id>/summary.json.

Usage:
    python scripts/honesty_check.py              # check the listed artifacts
    python scripts/honesty_check.py --self-test  # prove the check can fail
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
import unicodedata
from collections import defaultdict
from html.parser import HTMLParser
from pathlib import Path

from markdown_it import MarkdownIt

ROOT = Path(__file__).resolve().parent.parent
LIST_FILE = Path("docs") / "published.txt"

NUM = r"\d[\d,]*(?:\.\d+)?|\.\d+"
WORDNUM = (
    r"(?:one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve|fifteen|twenty"
    r"|thirteen|fourteen|sixteen|seventeen|eighteen|nineteen"
    r"|thirty|forty|fifty|sixty|seventy|eighty|ninety|hundred)"
)
SCALE = r"(?:\s*(?:thousand|million|billion|mn|bn|k|m))?"
MONEY_WORD = r"(?:USD|EUR|GBP|INR|JPY|dollars?|euros?|pounds?|rupees?|cents?)"
PER_K = r"(?:per|/)\s*(?:1[, ]?000|1k|1\s+thousand|one\s+thousand|thousand)\b"
METRIC_RE = re.compile(
    rf"(?:{NUM})\s*-?\s*(?:%|‰|percent(?:age[\s-]+points?)?\b|per\s?cent\b|pct\b)"  # percentages
    rf"|\b{WORDNUM}\s+(?:percent|per\s?cent)\b"  # "ten percent"
    rf"|(?:US\$|USD|EUR|GBP|INR|JPY|\$|€|£|₹|¥)\s*(?:{NUM})"  # money, symbol first
    rf"|(?:{NUM}){SCALE}\s*{MONEY_WORD}\b"  # money, unit after
    rf"|(?:{NUM})\s*(?:€|£|\$|₹|¥|¢)"  # money, symbol after
    rf"|(?:{NUM})-(?:dollar|euro|pound|rupee)\b"
    # a per-thousand rate: a number right before it (at most one word between) ...
    rf"|(?:{NUM})(?:\s+[A-Za-z][\w.-]*)?[\s|,(:=*/\u2013\u2014-]*{PER_K}"
    # ... or right after its noun: "per 1,000 alerts: 310", "per 1,000 alerts is 13.10"
    # (noun optional; table pipes, commas, brackets, dashes or emphasis may sit between)
    rf"|{PER_K}(?:\s+[A-Za-z][\w-]*){{0,3}}[\s|,(:=*\u2013\u2014-]*"
    rf"(?:\b(?:is|of|was|were|are)\b\s*)?(?:{NUM})",
    re.I,
)
LABEL_RE = re.compile(r"(?<![\w-])simulated\b", re.I)
# A negator voids a label later in the same sentence on the same line (conservative: it may void
# a label that was not really negated, which only forces a rewording). Sentences end at ". X",
# "! X", "? X" (X uppercase) or at "; " and ": ". Negators are looked for in all visible text,
# including code and inline HTML, so "<b>not</b> simulated" is caught.
# greedy, so every "simulated" later in the sentence is voided, not only the first
_GAP = r"(?:(?![.!?]\s+(?-i:[A-Z])|[;:]\s).)*"  # case-sensitive capital; no length cap
NEGATED_RE = re.compile(
    r"\b(?:not|no|non|none|never|cannot|without|nothing|neither|nor|zero|rather\s+than"
    r"|instead\s+of|ain'?t"
    r"|(?:is|was|are|were|does|do|did|has|have|had|ca|wo|could|would|should|must|need|sha)n'?t)\b"
    + _GAP
    + r"\bsimulated\b"
    r"|\b(?:un|non)-?simulated\b"
    r"|\bsimulated\s*[:=]\s*(?:no|false|0|none|n)\b"
    r"|\bsimulated(?:\s+\w+){0,5}\s+(?:was|were|is|are)(?:\s+(?:not|never)\b|n'?t\b)",
    re.I,
)
# text that is not prose even inside a text node: URLs (any scheme) and reference/footnote ids
NOT_PROSE_RE = re.compile(
    r"\b[a-z][a-z0-9+.-]{1,30}:(?://)?[^\s:]\S*|www\.\S+"  # any scheme, with or without //
    r"|[^\s()\[\]]*[/\\][^\s()\[\]]*"  # paths: data/simulated/run1, C:\data\simulated
    r"|\b[\w-]+(?:\.[A-Za-z][\w]{0,9})+\b"  # filenames, modules, bare domains: name.ext
    r"|\b[\w-]+(?:\.[\w-]+)+/\S*|(?<=\])\[[^\]]*\]|\[\^[^\]]*\]",
    re.I,
)
TAG_RE = re.compile(r"^<\s*(/)?\s*([A-Za-z][\w-]*)\b(?:[^>\"']|\"[^\"]*\"|'[^']*')*>$", re.S)
BREAK_TAGS = {"br", "img", "hr", "wbr"}  # render as a separation between words
ABBREV_RE = re.compile(
    r"\b(?:[A-Za-z]{1,2}\.){2,}"  # initialisms: U.S., J.P., e.g., i.e., Ph.D. (any case)
    r"|\b(?:etc|vs|cf|approx|St|Dr|Mr|Mrs|Ms|No|Inc|Ltd|Co|Corp|Jr|Sr|Mt|Prof|Fig|Gen|Gov"
    r"|Sen|Rep|Ave|Dept|Univ|Vol|Ch|Sec|Ref|Eq|Mio|Bn)\."
)
INVISIBLE = dict.fromkeys(map(ord, "\u034f\u115f\u1160\u3164\uffa0"), None)
VOID_TAGS = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "wbr"}
_MD = MarkdownIt("commonmark").enable("table")  # GFM tables, with or without outer pipes


def _norm(text: str) -> str:
    text = unicodedata.normalize("NFKC", text)  # fullwidth forms, NBSP, thin spaces -> ASCII
    text = "".join(c for c in text if unicodedata.category(c) != "Cf")  # zero-width, LRM ...
    text = text.translate(INVISIBLE)  # invisible fillers outside category Cf
    text = re.sub("[\u2010-\u2015\u2212]", "-", text)  # hyphen and dash variants
    for apostrophe in ("\u2019", "\u2018", "\u02bc", "\u2032", "`", "\u00b4", " \u0301"):
        text = text.replace(apostrophe, "'")
    return text


class ListingError(Exception):
    """docs/published.txt is missing or names a path outside the repo."""


def published_files(root: Path = ROOT) -> list[Path]:
    listing = root / LIST_FILE
    if not listing.is_file():
        raise ListingError(f"{LIST_FILE} is missing")
    out = []
    for raw in listing.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        line = re.split(r"\s+#", line, maxsplit=1)[0].strip()
        rel = Path(line)
        path = (root / rel).resolve()
        if rel.is_absolute() or not path.is_relative_to(root.resolve()):
            raise ListingError(f"{LIST_FILE}: {line} is outside the repo")
        out.append(root / rel)
    return out


Piece = tuple[str, bool]  # (visible text, may it count as a label?)

_WORD_UNITS = (
    r"USD|EUR|GBP|INR|JPY|percent(?:age)?|pct|dollars?|cents?|euros?|pounds?|rupees?"
    r"|per_?(?:1k|1000)"
)
TABLE_UNIT_RE = re.compile(
    rf"%|‰|\$|€|£|₹|¥|¢|(?<![A-Za-z])(?:{_WORD_UNITS})(?![A-Za-z])|"  # snake_case too
    # camelCase: recallPct, costUsd
    r"(?<=[a-z])(?-i:Usd|Eur|Gbp|Inr|Jpy|Pct|Percent(?:age)?|Dollars?|Cents?)(?![a-z])|"
    r"(?<=[a-z])(?-i:USD|EUR|GBP|INR|JPY|PCT)(?![a-z])|"
    # camelCase with the unit first: pctChange, usdCost, USDCost
    r"(?<![A-Za-z])(?:usd|eur|gbp|inr|jpy|pct|percent(?:age)?|dollars?|cents?|per_?(?:1k|1000))"
    r"(?=(?-i:[A-Z]))|" + PER_K,
    re.I,
)
NUMBER_CELL_RE = re.compile(rf"^\s*[~≈+\-]?\s*(?:{NUM})\s*$")
HIDDEN_TAGS = frozenset({"script", "style", "template"})


def _is_unit_label(cell: str) -> bool:
    return not NUMBER_CELL_RE.match(cell) and TABLE_UNIT_RE.search(cell) is not None


def _row_metric_indices(
    cells: list[str], headers: list[str], table_unit: bool = False
) -> list[int]:
    """Indices of a row's number cells that are metrics: another cell in the row names a unit
    (`Recall (%) | 97.5`, `13.10 | USD`), the cell's column header names one, the table's
    corner (first header cell) does (`| Recall (%) | Model A | Model B |`), or the table's
    title row or caption does (`table_unit`)."""
    row_unit = table_unit or any(_is_unit_label(c) for c in cells)
    corner_unit = bool(headers) and _is_unit_label(headers[0])
    out = []
    for k, cell in enumerate(cells):
        if NUMBER_CELL_RE.match(cell):
            header = headers[k] if k < len(headers) else ""
            if row_unit or corner_unit or TABLE_UNIT_RE.search(header):
                out.append(k)
    return out


def _row_metrics(cells: list[str], headers: list[str]) -> list[str]:
    return [cells[k].strip() for k in _row_metric_indices(cells, headers)]


def _clean_html(block: str) -> str:
    """Normalise HTML5 comment forms (so the result does not depend on the Python patch
    version's html.parser) and encoded newlines (not source line breaks)."""
    block = re.sub(r"<!--->|<!-->", "<!---->", block).replace("--!>", "-->")
    return re.sub(r"&#0*10;|&#[xX]0*[aA];|&NewLine;", " ", block)


class _HtmlText(HTMLParser):
    """Visible text of one HTML block, as a browser shows it: entities decoded, comments
    (including `<!-->`) dropped, script/style/template content skipped, quoted attributes
    and a literal `<` handled by the standard library parser."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[tuple[int, str]] = []
        self._hidden = 0

    def handle_starttag(self, tag, attrs):  # type: ignore[no-untyped-def]
        self._hidden += tag in HIDDEN_TAGS

    def handle_endtag(self, tag):  # type: ignore[no-untyped-def]
        if tag in HIDDEN_TAGS and self._hidden:
            self._hidden -= 1

    def handle_data(self, data):  # type: ignore[no-untyped-def]
        if not self._hidden:
            self.parts.append((self.getpos()[0] - 1, data))


def _html_text(block: str) -> list[tuple[int, str]]:
    """(0-based line within the block, visible text) pieces of an HTML block."""
    parser = _HtmlText()
    parser.feed(_clean_html(block))
    if not parser.rawdata.startswith("<!--"):  # an unclosed comment hides the rest; else flush
        parser.close()
    return parser.parts


class _DocTables(HTMLParser):
    """Every table of the rendered document, read the way a browser builds it: one HTML stream
    for the whole file, so a table spread over several Markdown blocks (Markdown inside a
    cell, blank lines between rows) stays one table; a <td>/<th> with no open row starts one
    (the browser's implied <tr>). Source lines come from markers added before rendering.
    Result: `metrics` maps a 0-based source line to the metric number cells on it."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.metrics: dict[int, list[str]] = defaultdict(list)
        self.rows: set[int] = set()  # source lines that hold a table row
        self._hidden = 0
        self._mark = (1, 0, False)  # (rendered line, source line, offset within raw HTML?)
        self._tables: list[dict] = []

    def _line(self) -> int:
        rendered, source, offset = self._mark
        return source + (self.getpos()[0] - rendered if offset else 0)

    def handle_comment(self, data):  # type: ignore[no-untyped-def]
        if data.startswith("L:"):  # start of a raw HTML block: lines run on from here
            self._mark = (self.getpos()[0], int(data[2:]), True)

    def handle_starttag(self, tag, attrs):  # type: ignore[no-untyped-def]
        line = dict(attrs).get("data-line")
        if line is not None and line.isdigit():  # a rendered Markdown block: fixed line
            self._mark = (self.getpos()[0], int(line), False)
        self._hidden += tag in HIDDEN_TAGS
        t = self._tables[-1] if self._tables else None
        if tag == "table":
            self._tables.append(
                {
                    "events": [],  # ("header" | "data", cell texts, cells), judged at the end
                    "headers_seen": False,
                    "seen_data": False,
                    "unit": False,  # a title row or caption names a unit for the whole table
                    "thead": False,
                    "row": None,
                    "cell": None,
                    "caption": None,
                }
            )
            return
        if tag == "caption":
            if t is not None:
                self._end_row(t)  # the browser closes an open cell and row before a caption
                t["caption"] = []
            return
        if t is not None and t["caption"] is not None and tag in self.CAPTION_ENDERS:
            self._end_caption(t)  # the browser closes an omitted </caption> here
        if t is None:
            return
        if tag == "thead":
            self._end_row(t)
            t["thead"] = True
        elif tag in ("tbody", "tfoot"):
            self._end_row(t)
            t["thead"] = False
        elif tag == "tr":
            self._end_row(t)
            t["row"] = []
        elif tag in ("td", "th"):
            self._end_cell(t)
            if t["row"] is None:
                t["row"] = []  # the browser's implied <tr>
            t["cell"] = ([], tag == "th", self._line())

    def handle_endtag(self, tag):  # type: ignore[no-untyped-def]
        if tag in HIDDEN_TAGS and self._hidden:
            self._hidden -= 1
        if not self._tables:
            return
        t = self._tables[-1]
        if tag == "caption" and t["caption"] is not None:
            self._end_caption(t)
        elif tag in ("td", "th"):
            self._end_cell(t)
        elif tag == "tr":
            self._end_row(t)
        elif tag == "thead":
            self._end_row(t)
            t["thead"] = False
        elif tag == "table":
            self._finish(self._tables.pop())

    def handle_data(self, data):  # type: ignore[no-untyped-def]
        if not self._tables or self._hidden:
            return
        t = self._tables[-1]
        if t["cell"] is not None:
            t["cell"][0].append(data)
        elif t["caption"] is not None:
            t["caption"].append(data)

    def close(self) -> None:
        super().close()
        while self._tables:  # a table left open at the end: the browser still shows its rows
            self._finish(self._tables.pop())

    CAPTION_ENDERS = frozenset({"tr", "td", "th", "thead", "tbody", "tfoot", "colgroup", "col"})

    @staticmethod
    def _end_caption(t: dict) -> None:
        if t["caption"] is not None:
            t["unit"] = t["unit"] or _is_unit_label(_norm(" ".join(t["caption"])))
        t["caption"] = None

    def _finish(self, t: dict) -> None:
        """Judge a table once it has ended, so a caption anywhere in it counts."""
        self._end_caption(t)
        self._end_row(t)
        headers: list[str] = []
        prev_header = False
        for kind, texts, row in t["events"]:
            if kind == "header":
                # a later header-shaped row is judged against the headers read so far (column
                # header and corner), so an all-<th> value row is still checked
                indices = _row_metric_indices(texts, headers, t["unit"])
                if prev_header:  # consecutive header rows merge column by column
                    width = max(len(headers), len(texts))
                    old = headers + [""] * (width - len(headers))
                    new = texts + [""] * (width - len(texts))
                    headers = [
                        " ".join(x for x in pair if x) for pair in zip(old, new, strict=True)
                    ]
                else:
                    headers = texts
                prev_header = True
            else:
                prev_header = False
                indices = _row_metric_indices(texts, headers, t["unit"])
            for k in indices:
                self.metrics[row[k][2]].append(texts[k])

    @staticmethod
    def _end_cell(t: dict) -> None:
        if t["cell"] is not None and t["row"] is not None:
            parts, is_th, line = t["cell"]
            t["row"].append((_norm(" ".join(parts)).strip(), is_th, line))
        t["cell"] = None

    def _end_row(self, t: dict) -> None:
        self._end_cell(t)
        row, t["row"] = t["row"], None
        if not row:
            return
        texts = [c[0] for c in row]
        self.rows.update(c[2] for c in row)
        filled = [is_th for text, is_th, _ in row if text]
        if not filled:
            return  # an empty spacer row
        has_number = any(NUMBER_CELL_RE.match(x) for x in texts)
        # a header row: inside <thead> (unless it holds numbers under headers already read, as
        # when </thead> is omitted), or, before any data row, a row of two or more cells whose
        # filled cells are all <th> (an empty corner <td> is allowed); once data rows have
        # started, every row outside <thead> is data. A one-cell row is a title or section
        # label: before headers and data it lends its unit to the whole table.
        in_head = t["thead"] and not (has_number and t["headers_seen"])
        if in_head or (not t["seen_data"] and all(filled) and len(row) >= 2):
            t["headers_seen"] = True
            t["events"].append(("header", texts, row))
        elif len(row) == 1 and not has_number:
            if not t["headers_seen"] and not t["seen_data"]:
                t["unit"] = t["unit"] or _is_unit_label(texts[0])
        else:
            t["seen_data"] = True
            t["events"].append(("data", texts, row))


def _doc_tables(text: str) -> _DocTables:
    tokens = _MD.parse(text)
    for tok in tokens:
        if tok.map and tok.nesting == 1:
            tok.attrSet("data-line", str(tok.map[0]))
        if tok.type == "html_block" and tok.map:
            tok.content = f"<!--L:{tok.map[0]}-->" + _clean_html(tok.content)
    parser = _DocTables()
    parser.feed(_MD.renderer.render(tokens, _MD.options, {}))
    parser.close()
    return parser


def _visible_lines(text: str) -> dict[int, list[Piece]]:
    """Parse Markdown as CommonMark does and return, per 0-based source line, the visible text
    in order as pieces joined with no separator, each marked whether a label may come from it
    (prose text nodes: not code, inline HTML elements, autolinks or images)."""
    lines: dict[int, list[Piece]] = defaultdict(list)
    row_line = 0
    for tok in _MD.parse(text):
        if tok.type == "tr_open":
            row_line = tok.map[0] if tok.map else 0
        elif tok.type in ("th_open", "td_open"):
            lines[row_line].append((" | ", False))
        if tok.map is None:
            continue
        start = tok.map[0]
        if tok.type in ("fence", "code_block"):
            first = start + (1 if tok.type == "fence" else 0)
            for k, line in enumerate(tok.content.split("\n")):
                lines[first + k].append((_norm(line), False))
        elif tok.type == "html_block":
            for line0, data in _html_text(tok.content):
                for k, seg in enumerate(data.split("\n")):
                    lines[start + line0 + k] += [(" ", False), (_norm(seg), False)]
        elif tok.type == "inline":
            children = tok.children or []
            breaks = sum(c.type in ("softbreak", "hardbreak") for c in children)
            breaks += sum(c.content.count("\n") for c in children if c.type == "html_inline")
            # a break inside a code span, link title or image alt is not reported by the
            # parser; then lines may be misattributed, so no label in this paragraph counts
            trusted = tok.content.count("\n") == breaks
            line, stack, autolink = start, [], False
            for ch in children:
                if ch.type in ("softbreak", "hardbreak"):
                    line += 1
                elif ch.type in ("text", "text_special"):
                    ok = trusted and not stack and not autolink
                    lines[line].append((_norm(ch.content.replace("\n", " ")), ok))
                elif ch.type == "code_inline":
                    lines[line].append((_norm(ch.content), False))
                elif ch.type == "html_inline":
                    m = TAG_RE.match(ch.content)
                    if m and m.group(2).lower() in BREAK_TAGS:
                        lines[line].append((" ", False))
                    if m and not ch.content.startswith("<!--"):
                        closing, name = m.group(1), m.group(2).lower()
                        if closing:
                            if name in stack:  # a stray closing tag closes nothing
                                del stack[len(stack) - 1 - stack[::-1].index(name) :]
                        elif name not in VOID_TAGS:  # browsers ignore "/>" on non-void tags
                            stack.append(name)
                    line += ch.content.count("\n")
                elif ch.type == "link_open":
                    autolink = ch.markup == "autolink"
                elif ch.type == "link_close":
                    autolink = False
                elif ch.type == "image":  # alt text is not visible prose; the image separates
                    lines[line].append((" ", False))
    return lines


def _labelled(pieces: list[Piece]) -> bool:
    text = "".join(t for t, _ in pieces)
    ok = [flag for t, flag in pieces for _ in t]
    blocked = [False] * len(text)
    # abbreviations such as "e.g." do not end a sentence (same length, so positions hold)
    scan = ABBREV_RE.sub(lambda m: m.group(0).replace(".", "_"), text)
    for rx, source in ((NOT_PROSE_RE, text), (NEGATED_RE, scan)):
        for m in rx.finditer(source):
            blocked[m.start() : m.end()] = [True] * (m.end() - m.start())
    return any(
        all(ok[k] and not blocked[k] for k in range(m.start(), m.end()))
        for m in LABEL_RE.finditer(text)
    )


def _line_problems(text: str) -> list[tuple[int, str]]:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # CommonMark 0.31.2 ends an HTML comment at the first "-->", even inside "--->";
    # markdown-it-py's inline rule does not, so normalise longer closers first (line count kept)
    text = re.sub(r"-{3,}>", "-->", text)
    lines = _visible_lines(text)
    tables = _doc_tables(text)
    found = []
    for line in sorted(set(lines) | set(tables.metrics)):
        pieces = lines.get(line, [])
        seen = "".join(t for t, _ in pieces)
        metrics = [m.group(0).strip() for m in METRIC_RE.finditer(seen)]
        if line in tables.rows or line in tables.metrics:  # table cells: rows and headers
            extra = tables.metrics.get(line, [])
        elif "|" in seen:  # pipe text that is not a GFM table still shows unit and number
            extra = _row_metrics([c for c in seen.strip().strip("|").split("|")], [])
        else:
            extra = []
        metrics += [n for n in extra if not any(n in m for m in metrics)]
        if metrics and not _labelled(pieces):
            found.extend((line + 1, m) for m in metrics)
    return found


GROUP_TAGS = frozenset({"section", "header", "footer"})


class _HtmlGroups(HTMLParser):
    """Visible text of an HTML page, grouped by its top-level <section>, <header> and <footer>
    (text outside them is one more group). A generated page states the simulated label once per
    panel, so for `.html` files the label is judged per group, not per source line."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.groups: list[tuple[int, list[str]]] = [(1, [])]
        self._depth = 0
        self._hidden = 0

    def handle_starttag(self, tag, attrs):  # type: ignore[no-untyped-def]
        self._hidden += tag in HIDDEN_TAGS
        if tag in GROUP_TAGS:
            if self._depth == 0:
                self.groups.append((self.getpos()[0], []))
            self._depth += 1

    def handle_endtag(self, tag):  # type: ignore[no-untyped-def]
        if tag in HIDDEN_TAGS and self._hidden:
            self._hidden -= 1
        if tag in GROUP_TAGS and self._depth:
            self._depth -= 1
            if self._depth == 0:
                self.groups.append((self.getpos()[0], []))

    def handle_data(self, data):  # type: ignore[no-untyped-def]
        if not self._hidden and data.strip():
            self.groups[-1][1].append(_norm(data.strip()))


def _html_problems(text: str) -> list[tuple[int, str]]:
    """Every metric in an HTML group needs a visible, un-negated "simulated" in that group.
    Text nodes are joined by newlines, so a negator in one node never voids a label in another."""
    parser = _HtmlGroups()
    parser.feed(_clean_html(text))
    parser.close()
    found = []
    for line, nodes in parser.groups:
        joined = "\n".join(nodes)
        metrics = [m.group(0).strip() for m in METRIC_RE.finditer(joined)]
        if metrics and not _labelled([(joined, True)]):
            found.extend((line, m) for m in metrics)
    return found


def check(files: list[Path], root: Path = ROOT) -> list[str]:
    problems: list[str] = []
    for path in files:
        rel = path.relative_to(root) if path.is_relative_to(root) else path
        if not path.is_file():
            problems.append(f"{rel}: listed but missing")
            continue
        body = path.read_text(encoding="utf-8")
        found = _html_problems(body) if path.suffix == ".html" else _line_problems(body)
        for lineno, metric in found:
            problems.append(f"{rel}:{lineno}: {metric} has no simulated label")
    return problems


